const LANGUAGES: Record<string, Strings> = { en, de, el };

let strings: Strings = en;
let locale = "en";

/** Picks the UI language from the Home Assistant profile (falls back to English). */
export function setLanguage(hass: HomeAssistant | undefined): void {
  const lang = (hass?.locale?.language ?? hass?.language ?? "en").toLowerCase();
  const base = lang.split("-")[0];
  strings = LANGUAGES[base] ?? en;
  locale = lang;
}

/** Current UI strings. */
export const t = (): Strings => strings;

/** Number with fixed decimals in the user's locale. */
export const num: Fmt = (v, digits = 1) =>
  v.toLocaleString(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits });

/** Parses user input with either decimal separator. */
export const parseNum = (s: string): number => Number(s.replace(/\s/g, "").replace(",", "."));

/** Locale for sorting names. */
export const collator = (): string => locale;
